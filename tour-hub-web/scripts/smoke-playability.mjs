import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'

const { chromium } = await import(process.env.TIMEWALKER_PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.TIMEWALKER_BASE_URL || 'http://127.0.0.1:5173'
const output = process.env.TIMEWALKER_TEST_OUTPUT || '/tmp/timewalker-playability'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: process.env.TIMEWALKER_CHROMIUM, args: ['--no-sandbox'] })
const errors = []
let modelRequests = 0
async function pageFor(width = 390, missingPhotos = false) {
  const context = await browser.newContext({ viewport: { width, height: 844 }, hasTouch: true, reducedMotion: 'reduce', acceptDownloads: true })
  await context.addInitScript(() => {
    window.__copiedJournal = ''
    window.__speechCount = 0
    Object.defineProperty(navigator, 'share', { configurable: true, value: undefined })
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.__copiedJournal = text } } })
    Object.defineProperty(window, 'speechSynthesis', { configurable: true, value: { getVoices: () => [], speak: utterance => { window.__speechCount++; queueMicrotask(() => utterance.onerror?.(new Event('error'))) }, cancel: () => {} } })
  })
  const page = await context.newPage()
  page.on('pageerror', e => errors.push(e.message))
  await page.route('**/api/**', route => { modelRequests++; return route.abort() })
  if (missingPhotos) await page.route('**/spots/**', route => route.fulfill({ status: 404, body: 'test missing photo' }))
  return page
}
